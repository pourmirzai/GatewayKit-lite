/*
 |------------------------------------------------------------------------------------------------------------------------------------------
 | Freemius SDK (parent product — GatewayKit)
 |------------------------------------------------------------------------------------------------------------------------------------------
 | The Freemius SDK is loaded via Composer (vendor/freemius/wordpress-sdk) and
 | is shipped inside the Lite ZIP so it works on sites without Composer. The
 | autoloader must be required BEFORE the snippet so fs_dynamic_init() is
 | available. The snippet below was generated by the Freemius dashboard for the
 | "GatewayKit" parent product (id 34906, slug 'gatewaykit'); the menu slug
 | matches the real GatewayKit admin menu (src/Core/class-plugin.php:326).
 |
 | `has_addons => true` triggers the native "Add-Ons" submenu where users can
 | purchase/activate the GatewayKit Pro add-on. `has_paid_plans => false` keeps
 | the parent forever free — all monetization flows through the add-on.
 */
// Load the Composer autoloader for the bundled Freemius SDK.
//
// IMPORTANT (ERR-023): this MUST be guarded by a sentinel constant. The
// GatewayKit Pro add-on ships its own byte-identical vendor/ (same committed
// composer.lock), so its vendor/composer/autoload_real.php declares the SAME
// `ComposerAutoloaderInit<hash>` class. `require_once` only dedupes by file
// path, and Lite (`gatewaykit/vendor/autoload.php`) vs Pro
// (`gatewaykit-pro/vendor/autoload.php`) are different paths — without the
// sentinel, whichever plugin loads second fatals with
// "Cannot declare class ComposerAutoloaderInit...". The sentinel is
// load-order independent: the first of Lite/Pro to run loads the autoloader
// and sets the constant; the other skips it (the Freemius classes are already
// registered on spl_autoload). Because composer.lock is committed, the SDK is
// guaranteed byte-identical between the two ZIPs.
