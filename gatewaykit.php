/*
 |------------------------------------------------------------------------------------------------------------------------------------------
 | Uninstall cleanup (Freemius `after_uninstall`)
 |------------------------------------------------------------------------------------------------------------------------------------------
 | WordPress only fires ONE uninstall handler per plugin: if `uninstall.php`
 | exists it runs INSTEAD of registered `register_uninstall_hook()` callbacks,
 | which means Freemius's uninstall-tracking hook never runs and we lose churn
 | analytics. To let Freemius report the uninstall event to its server AND run
 | our cleanup afterward, we delete `uninstall.php` and register the cleanup
 | function on Freemius's `after_uninstall` action (see ARCH-021). The cleanup
 | logic is identical to the old `uninstall.php` and remains opt-in via the
 | `gatewaykit_delete_data_on_uninstall` option.
 */
if ( ! function_exists( 'gatewaykit_lite_uninstall_cleanup' ) ) {
	/**
	 * Complete opt-in cleanup of all GatewayKit data on uninstall.
	 *
	 * Runs only when an administrator has explicitly enabled it beforehand via
	 * the "Remove all GatewayKit data on deletion" setting (option
	 * `gatewaykit_delete_data_on_uninstall`). When the option is absent or false,
	 * all data is preserved so users can reinstall without losing transactions.
	 *
	 * @return void
	 */
	function gatewaykit_lite_uninstall_cleanup() {
		if ( get_option( 'gatewaykit_delete_data_on_uninstall' ) !== '1' ) {
			return;
		}

		global $wpdb;

		// 1. Drop custom database tables.
		$gatewaykit_tables = array(
			$wpdb->prefix . 'gatewaykit_payment_transactions',
			$wpdb->prefix . 'gatewaykit_payment_logs',
			$wpdb->prefix . 'gatewaykit_discounts',
			$wpdb->prefix . 'gatewaykit_discount_usage',
			$wpdb->prefix . 'gatewaykit_transaction_notes',
		);

		foreach ( $gatewaykit_tables as $gatewaykit_table ) {
			$wpdb->query( $wpdb->prepare( 'DROP TABLE IF EXISTS %i', $gatewaykit_table ) ); // phpcs:ignore WordPress.DB.DirectDatabaseQuery.SchemaChange, WordPress.DB.DirectDatabaseQuery.NoTruncation, WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
		}

		// 1b. Delete sample forms and receipt page if created.
		$receipt_page_id = (int) get_option( 'gatewaykit_receipt_page_id', 0 );
		if ( $receipt_page_id ) {
			wp_delete_post( $receipt_page_id, true );
		}
		$default_form_ids = (array) get_option( 'gatewaykit_default_form_ids', array() );
		foreach ( $default_form_ids as $form_id ) {
			if ( $form_id ) {
				wp_delete_post( (int) $form_id, true );
			}
		}

		// 2. Delete all gatewaykit_* options.
		$gatewaykit_option_names = $wpdb->get_col( // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
			$wpdb->prepare(
				'SELECT option_name FROM %i WHERE option_name LIKE %s',
				$wpdb->options,
				$wpdb->esc_like( 'gatewaykit_' ) . '%'
			)
		);

		if ( ! empty( $gatewaykit_option_names ) ) {
			foreach ( $gatewaykit_option_names as $gatewaykit_option_name ) {
				delete_option( $gatewaykit_option_name );
			}
		}

		// 3. Delete all gatewaykit_* transients (stored in options with/without prefix).
		$gatewaykit_transient_names = $wpdb->get_col( // phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
			$wpdb->prepare(
				'SELECT option_name FROM %i WHERE option_name LIKE %s OR option_name LIKE %s',
				$wpdb->options,
				$wpdb->esc_like( '_transient_gatewaykit_' ) . '%',
				$wpdb->esc_like( '_transient_timeout_gatewaykit_' ) . '%'
			)
		);

		if ( ! empty( $gatewaykit_transient_names ) ) {
			foreach ( $gatewaykit_transient_names as $gatewaykit_transient_option ) {
				delete_option( $gatewaykit_transient_option );
			}
		}

		// 4. Clear any scheduled cron events registered by the plugin.
		$gatewaykit_cron = get_option( 'cron', array() );
		if ( is_array( $gatewaykit_cron ) ) {
			foreach ( $gatewaykit_cron as $gatewaykit_timestamp => $gatewaykit_hooks ) {
				if ( ! is_array( $gatewaykit_hooks ) ) {
					continue;
				}
				foreach ( array_keys( $gatewaykit_hooks ) as $gatewaykit_hook ) {
					if ( 0 === strpos( $gatewaykit_hook, 'gatewaykit_' ) ) {
						wp_clear_scheduled_hook( $gatewaykit_hook );
					}
				}
			}
		}
	}
}

