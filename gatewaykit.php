/*
|------------------------------------------------------------------------------------------------------------------------------------------
| Pro license detection helpers (Lite-side)
|------------------------------------------------------------------------------------------------------------------------------------------
| The real license gate lives in `gatewaykit_pro_is_licensed()` inside the
| Pro add-on (gatewaykit-pro.php), but that function only exists AFTER the
