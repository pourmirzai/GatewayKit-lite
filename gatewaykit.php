| `gatewaykit_pro_is_licensed()` instead.
 */
if ( ! function_exists( 'gatewaykit_is_pro_licensed' ) ) {
	/**
	 * Detect whether GatewayKit Pro is installed AND has a valid paying license.
	 *
	 * @return bool
	 */
	function gatewaykit_is_pro_licensed() {
		return function_exists( 'gatewaykit_pro_is_licensed' )
			&& gatewaykit_pro_is_licensed();
	}
}

if ( ! function_exists( 'gatewaykit_get_upgrade_url' ) ) {
	/**
	 * Return the best available upgrade URL for sending Lite users to Pro checkout.
	 *
	 * Preference order:
	 *  1. The Pro add-on SDK's native upgrade URL (most accurate — deep-links
	 *     into the Pro checkout with the current install's billing context).
	 *  2. The parent Freemius SDK's Add-Ons page (used when the Pro add-on
	 *     is not yet installed — this is the typical Lite-only user state).
	 *  3. The public marketing site as a hard fallback.
	 *
	 * @return string
	 */
	function gatewaykit_get_upgrade_url() {
		if ( function_exists( 'gatewaykit_pro_fs' ) ) {
			return gatewaykit_pro_fs()->get_upgrade_url();
		}
		if ( function_exists( 'gatewaykit_fs' ) ) {
			return gatewaykit_fs()->get_addons_url();
		}
		return 'https://pourmirzai.com/gatewaykit/';
	}
}

if ( ! function_exists( 'gatewaykit_fputcsv' ) ) {
	/**
	 * Write an array row as CSV to an open file pointer.
	 *
	 * Lightweight wrapper around PHP's fputcsv(). All GatewayKit CSV exports
	 * (transactions, logs) funnel through this helper so encoding and
	 * delimiter behavior stays consistent in one place.
	 *
	 * @param resource $handle Open file pointer.
	 * @param array    $fields Row values.
	 * @return int|false Bytes written, or false on failure.
	 */
	function gatewaykit_fputcsv( $handle, array $fields ) {
		// Mitigate CSV formula injection: prefix cells starting with
		// dangerous characters with a single quote so spreadsheet
		// applications treat them as text, not formulas.
		$fields = array_map(
			function ( $value ) {
				if ( is_string( $value ) && '' !== $value ) {
						$first = $value[0];
					if ( false !== strpos( "=+-@\t\r", $first ) ) {
						$value = "'" . $value;
					}
				}
				return $value;
			},
			$fields
		);

		return fputcsv( $handle, $fields );
	}
}

